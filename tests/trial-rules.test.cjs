const assert = require('node:assert/strict');
const { guilty, angleDelta, random, gifts } = require('../trial-rules.js');
const statue = { x: 0, y: 0, angle: Math.PI / 2, range: 420, half: .65 };
const actor = { x: 0, y: 100, facing: -Math.PI / 2, hp: 100 };
assert(guilty(statue, actor), 'mutual gaze is punishable');
assert(!guilty(statue, {...actor, facing: Math.PI / 2}), 'facing away is safe under original edict');
assert(guilty(statue, {...actor, facing: Math.PI / 2}, 'back'), 'amended edict punishes facing away');
assert(!guilty(statue, actor, 'back'), 'amended edict protects direct gaze');
assert(!guilty(statue, {...actor, player: true}, 'demons'), 'demons-only exempts player');
assert(guilty(statue, actor, 'demons'), 'demons-only still punishes monsters');
assert(!guilty(statue, {...actor, paper: true}), 'paper is not a living actor');
assert(!guilty(statue, {...actor, blind: true}, 'back'), 'closed eyes exempt both gaze edicts');
assert(!guilty(statue, {...actor, x: 500}), 'outside cone');
assert(!guilty(statue, {...actor, y: 500}), 'outside range');
assert(Math.abs(angleDelta(-Math.PI + .1, Math.PI - .1) - .2) < 1e-8, 'angles wrap across pi');
const a=random('same'), b=random('same'), c=random('different');
for(let i=0;i<20;i++)assert.equal(a(),b());
assert.notEqual(a(),c());assert.equal(new Set(gifts.map(g=>g.id)).size,6);
console.log('Trial geometry, exceptions, seed and gift identity checks passed.');
